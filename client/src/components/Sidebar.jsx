const baseLinks = [
  { to: '/',             label: 'Dashboard',       icon: icons.dashboard },
  { to: '/timetable',    label: 'Timetable',       icon: icons.calendar },
  { to: '/attendance',   label: 'Attendance',      icon: icons.checkCircle },
  { to: '/marks',        label: 'Marks & Ranking', icon: icons.barChart },
  { to: '/career',       label: 'Career',          icon: icons.rocket },
  { to: '/scheduler',    label: 'Scheduler',       icon: icons.clock },
  { to: '/profile',      label: 'Settings',        icon: icons.settings },
  { to: '/ai-assistant', label: 'AI Assistant',    icon: icons.bot },
  { to: '/prediction',   label: 'Predictor',       icon: icons.target },
];

export default function Sidebar() {
  const { user, logout } = useAuth();
  const [open, setOpen] = useState(false);

  const links = user?.role === 'teacher'
    ? [...baseLinks, { to: '/admin', label: 'User Management', icon: icons.users }]
    : baseLinks;

  const initials = user?.name
    ? user.name.split(' ').map(n => n[0]).join('').slice(0, 2).toUpperCase()
    : '?';

  const handleLinkClick = () => {
    if (window.innerWidth <= 768) setOpen(false);
  };

  useEffect(() => {
    const onResize = () => { if (window.innerWidth > 768) setOpen(false); };
    window.addEventListener('resize', onResize);
    return () => window.removeEventListener('resize', onResize);
  }, []);

  useEffect(() => {
    document.body.style.overflow = open ? 'hidden' : '';
    return () => { document.body.style.overflow = ''; };
  }, [open]);

  return (
    <>
      {/* Mobile top navbar */}
      <nav className="mobile-navbar">
        <span className="mobile-nav-logo">
          <span style={{
            width: 24,
            height: 24,
            borderRadius: 6,
            background: 'linear-gradient(135deg, #8b5cf6 0%, #3b82f6 100%)',
            display: 'inline-block',
          }} />
          StudentAI
        </span>
        <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
          <button
            onClick={logout}
            style={{
              background: 'rgba(239, 68, 68, 0.1)',
              border: '1px solid rgba(239, 68, 68, 0.2)',
              borderRadius: 6,
              color: '#f87171',
              padding: '8px 12px',
              fontSize: 13,
              fontWeight: 600,
              cursor: 'pointer',
              display: 'flex',
              alignItems: 'center',
              gap: 6,
              transition: 'all 0.15s ease',
            }}
            title="Logout"
          >
            {icons.logout}
            <span>Logout</span>
          </button>
          <button
            className="mobile-menu-btn"
            onClick={() => setOpen(o => !o)}
            aria-label="Toggle menu"
          >
            {open ? icons.close : icons.menu}
          </button>
        </div>
      </nav>

      {/* Overlay */}
      {open && (
        <div
          className="sidebar-overlay"
          onClick={() => setOpen(false)}
        />
      )}

      {/* Sidebar */}
      <aside className={`sidebar${open ? ' open' : ''}`}>
        <div className="sidebar-logo">StudentAI</div>

        {/* User Card */}
        <div className="sidebar-user">
          <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
            <div style={{
              width: 36,
              height: 36,
              borderRadius: 8,
              background: 'linear-gradient(135deg, #8b5cf6 0%, #3b82f6 100%)',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              fontSize: 13,
              fontWeight: 700,
              color: '#fff',
              flexShrink: 0,
              boxShadow: '0 2px 8px rgba(139, 92, 246, 0.3)',
            }}>
              {initials}
            </div>
            <div style={{ minWidth: 0, flex: 1 }}>
              <div className="sidebar-user-name">{user?.name}</div>
              <div className="sidebar-user-email">{user?.email}</div>
            </div>
          </div>
        </div>

        <div className="sidebar-section-label">Navigation</div>

        {/* Nav Links */}
        <nav style={{ display: 'flex', flexDirection: 'column', gap: 2, flex: 1 }}>
          {links.map(l => (
            <NavLink
              key={l.to}
              to={l.to}
              end={l.to === '/'}
              className={({ isActive }) => `sidebar-link${isActive ? ' active' : ''}`}
              onClick={handleLinkClick}
            >
              <span className="sidebar-link-icon">{l.icon}</span>
              {l.label}
            </NavLink>
          ))}
        </nav>

        {/* Logout Button */}
        <button className="sidebar-logout" onClick={logout}>
          {icons.logout}
          Sign out
        </button>
      </aside>
    </>
  );
}
